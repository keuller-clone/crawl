"""Crawl's samples (the SAMPLE source, firmware/src/dsp/samplefx.c) -> firmware/src/dsp/crawl_samples.h.

  python3 tools/crawl_samples.py          (needs nothing but Python 3; the same bytes every time)

Each sample is a CC0 recording in assets/samples/, logged in assets/SAMPLES.md. It is mixed to mono, resampled to
22050 Hz, normalized (peak 30000), and coded as 4-bit IMA ADPCM, low nibble first, from predictor 0 / step index 0:
GR!MM's slot format (its samples.c), coded by Felucca's tools/sampleio.py. The samples live in the image, so what
GR!MM works out at boot is made here: the seek index (the decoder's state before every 256th sample) and the
decoder's two tables.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import sampleio as sio  # noqa: E402

RATE = 22050
SEG = 256
# (file in assets/samples/, name, root: the MIDI note that plays it as recorded)
SAMPLES = [
    ("m-soft.wav", "M-SOFT", 60),
]


def carray(ctype, name, v, per=32):
    lines = [",".join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return f"static const {ctype} {name}[{len(v)}] = {{\n" + ",\n".join(lines) + "};"


def main():
    out = ["/* Generated by tools/crawl_samples.py from assets/samples/ (do not edit). Crawl's samples, CC0 1.0",
           " * (assets/SAMPLES.md, LICENSES/CC0-1.0.txt): 22050 Hz mono IMA ADPCM, low nibble first, from predictor 0 /",
           " * step index 0, with the decoder's state before every 256th sample (samplefx.c). */",
           "#pragma once",
           "#include <stdint.h>",
           "/* the IMA ADPCM decoder as two tables (GR!MM's ima_init): for each step index and the code's low 3 bits,",
           " * the difference and the next step index */",
           carray("uint16_t", "SMP_VD", sio._IMA_VD, 16),
           carray("uint8_t", "SMP_NX", sio._IMA_NX, 32)]
    rows = []
    for k, (wav, name, root) in enumerate(SAMPLES):
        sr, x = sio.read_any_wav(ROOT / "assets" / "samples" / wav)
        s = sio.to_int16(sio.resample(x, sr, RATE))
        if len(s) & 1:
            s = s[:-1]
        data, _ = sio.ima_encode(s, 0)
        pred, idx, ip, ii, err = 0, 0, [], [], 0
        for n in range(len(s)):                     # decode it again: the seek index, and how close it is
            if n % SEG == 0:
                ip.append(pred)
                ii.append(idx)
            pred, idx = sio._ima_next(pred, idx, (data[n >> 1] >> (4 * (n & 1))) & 15)
            err += (pred - s[n]) ** 2
        sig = sum(v * v for v in s)
        print(f"sample {k}: {wav} -> {name}, {len(s) / RATE:.2f} s, {len(data)} B + {3 * len(ip)} B index, "
              f"ADPCM SNR {10 * __import__('math').log10(sig / max(1, err)):.1f} dB")
        out.append(f"/* {k}: {name}, assets/samples/{wav}, {len(s) / RATE:.2f} s, root {root} */")
        out.append(carray("uint8_t", f"SMP_D{k}", list(data)))
        out.append(carray("int16_t", f"SMP_P{k}", ip, 16))
        out.append(carray("uint8_t", f"SMP_I{k}", ii))
        rows.append(f'    {{SMP_D{k}, SMP_P{k}, SMP_I{k}, {len(s)}u, {root * 16}, "{name[:8]}"}},')
    out.append(f"#define SMP_N {len(SAMPLES)}u")
    out.append("static const struct {\n    const uint8_t *data;                        /* the ADPCM */\n"
               "    const int16_t *ipred;                       /* the decoder before segment k: its predictor, */\n"
               "    const uint8_t *iidx;                        /* .. its step index */\n"
               "    uint32_t n;                                 /* samples */\n"
               "    int16_t root16;                             /* the root, 1/16 semitone (MIDI x 16) */\n"
               "    char name[9];\n} SMP_TAB[SMP_N] = {")
    out += rows
    out.append("};")
    path = ROOT / "firmware" / "src" / "dsp" / "crawl_samples.h"
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{path.relative_to(ROOT)}: {path.stat().st_size} B")


if __name__ == "__main__":
    main()
